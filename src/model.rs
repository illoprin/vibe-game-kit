use std::{
    error::Error,
    fs,
    path::{Path, PathBuf},
};

use glam::{Mat4, Vec3};
use serde_json::Value;

use crate::{
    map::MaterialDef,
    mesh::add_box_materials_with_uv,
    obj,
    types::{Mesh, Vertex},
};

pub fn load_model(
    path: &Path,
    default_material: u32,
    materials: &[MaterialDef],
) -> Result<Mesh, Box<dyn Error>> {
    match path
        .extension()
        .and_then(|e| e.to_str())
        .unwrap_or("")
        .to_ascii_lowercase()
        .as_str()
    {
        "obj" => obj::load_obj(path, default_material),
        "mjson" | "json" => load_mjson(path, default_material, materials),
        ext => Err(format!("unsupported model format .{ext}: {}", path.display()).into()),
    }
}

pub fn place_model(mesh: &mut Mesh, position: [f32; 3], scale: f32) {
    mesh.transform(Mat4::from_scale_rotation_translation(
        Vec3::splat(scale),
        glam::Quat::IDENTITY,
        Vec3::from_array(position),
    ));
}

/// Adds textures referenced by a block-model JSON to the material array. The
/// texture path is resolved next to the model JSON (and missing PPMs are
/// generated by the texture cache when the GPU material array is created).
pub fn register_adjacent_textures(
    path: &Path,
    materials: &mut Vec<MaterialDef>,
) -> Result<(), Box<dyn Error>> {
    let extension = path
        .extension()
        .and_then(|extension| extension.to_str())
        .unwrap_or("")
        .to_ascii_lowercase();
    if extension != "json" && extension != "mjson" {
        return Ok(());
    }
    let root: Value = serde_json::from_str(&fs::read_to_string(path)?)?;
    let Some(textures) = root.get("textures").and_then(Value::as_object) else {
        return Ok(());
    };
    let base = path.parent().unwrap_or_else(|| Path::new("."));
    for value in textures.values().filter_map(Value::as_str) {
        let value = value.strip_prefix('#').unwrap_or(value);
        let tail = value.rsplit(['/', '\\', ':']).next().unwrap_or(value);
        if tail.is_empty() {
            continue;
        }
        let mut texture_file = PathBuf::from(tail);
        if texture_file.extension().is_none()
            || !texture_file
                .extension()
                .and_then(|extension| extension.to_str())
                .is_some_and(|extension| extension.eq_ignore_ascii_case("ppm"))
        {
            texture_file.set_extension("ppm");
        }
        let name = texture_file
            .file_stem()
            .and_then(|stem| stem.to_str())
            .unwrap_or(tail)
            .to_string();
        let texture_path = base.join(&texture_file);
        if materials
            .iter()
            .any(|material| material.texture == texture_path)
        {
            continue;
        }
        materials.push(MaterialDef {
            name,
            texture: texture_path,
        });
    }
    Ok(())
}

fn load_mjson(
    path: &Path,
    default_material: u32,
    materials: &[MaterialDef],
) -> Result<Mesh, Box<dyn Error>> {
    let root: Value = serde_json::from_str(&fs::read_to_string(path)?)?;
    let textures = root
        .get("textures")
        .and_then(Value::as_object)
        .cloned()
        .unwrap_or_default();
    let mut mesh = Mesh::default();
    let elements = root
        .get("elements")
        .and_then(Value::as_array)
        .ok_or("mjson requires an elements array")?;
    for element in elements {
        let from = vec3(element.get("from").ok_or("element missing from")?)?;
        let to = vec3(element.get("to").ok_or("element missing to")?)?;
        let center = Vec3::new(
            (from[0] + to[0]) / 32.0 - 0.5,
            (from[1] + to[1]) / 32.0 - 0.5,
            0.5 - (from[2] + to[2]) / 32.0,
        );
        let size = Vec3::new(
            (to[0] - from[0]) / 16.0,
            (to[1] - from[1]) / 16.0,
            (to[2] - from[2]) / 16.0,
        );
        let faces = element.get("faces").and_then(Value::as_object);
        let face_materials = ["north", "south", "east", "west", "up", "down"].map(|side| {
            faces
                .and_then(|faces| faces.get(side))
                .and_then(|face| face.get("texture"))
                .and_then(Value::as_str)
                .and_then(|texture| resolve_texture(texture, &textures, materials, path))
                .unwrap_or(default_material)
        });
        let face_uvs = ["north", "south", "east", "west", "up", "down"].map(|side| {
            faces
                .and_then(|faces| faces.get(side))
                .and_then(|face| face.get("uv"))
                .and_then(Value::as_array)
                .filter(|uv| uv.len() == 4)
                .and_then(|uv| {
                    Some([
                        uv[0].as_f64()? as f32 / 16.0,
                        uv[1].as_f64()? as f32 / 16.0,
                        uv[2].as_f64()? as f32 / 16.0,
                        uv[3].as_f64()? as f32 / 16.0,
                    ])
                })
        });
        let start = mesh.vertices.len();
        add_box_materials_with_uv(&mut mesh, center, size, face_materials, face_uvs);
        apply_element_rotation(element, &mut mesh.vertices[start..])?;
    }
    Ok(mesh)
}

fn apply_element_rotation(element: &Value, vertices: &mut [Vertex]) -> Result<(), Box<dyn Error>> {
    let Some(rotation) = element.get("rotation") else {
        return Ok(());
    };
    let raw_origin = vec3(rotation.get("origin").ok_or("rotation missing origin")?)?;
    let origin = Vec3::new(
        raw_origin[0] / 16.0 - 0.5,
        raw_origin[1] / 16.0 - 0.5,
        0.5 - raw_origin[2] / 16.0,
    );
    let axis = match rotation
        .get("axis")
        .and_then(Value::as_str)
        .ok_or("rotation missing axis")?
    {
        "x" => Vec3::X,
        "y" => Vec3::Y,
        "z" => Vec3::Z,
        _ => return Err("rotation axis must be x, y, or z".into()),
    };
    let angle = rotation
        .get("angle")
        .and_then(Value::as_f64)
        .ok_or("rotation missing angle")? as f32;
    let turn = glam::Quat::from_axis_angle(axis, angle.to_radians());
    for vertex in vertices {
        let point = Vec3::from_array(vertex.position);
        vertex.position = (origin + turn * (point - origin)).to_array();
        vertex.normal = (turn * Vec3::from_array(vertex.normal))
            .normalize()
            .to_array();
    }
    Ok(())
}

fn resolve_texture(
    texture: &str,
    textures: &serde_json::Map<String, Value>,
    materials: &[MaterialDef],
    model_path: &Path,
) -> Option<u32> {
    let key = texture.strip_prefix('#').unwrap_or(texture);
    let mut declared = textures.get(key).and_then(Value::as_str).unwrap_or(key);
    for _ in 0..8 {
        let Some(alias) = declared.strip_prefix('#') else {
            break;
        };
        let Some(next) = textures.get(alias).and_then(Value::as_str) else {
            break;
        };
        declared = next;
    }
    let tail = declared.rsplit(['/', '\\', ':']).next().unwrap_or(declared);
    let mut adjacent_file = PathBuf::from(tail);
    if adjacent_file.extension().is_none()
        || !adjacent_file
            .extension()
            .and_then(|extension| extension.to_str())
            .is_some_and(|extension| extension.eq_ignore_ascii_case("ppm"))
    {
        adjacent_file.set_extension("ppm");
    }
    let adjacent_path = model_path
        .parent()
        .unwrap_or_else(|| Path::new("."))
        .join(adjacent_file);
    if let Some(index) = materials
        .iter()
        .position(|material| material.texture == adjacent_path)
    {
        return Some(index as u32);
    }
    let stem = Path::new(tail)
        .file_stem()
        .and_then(|s| s.to_str())
        .unwrap_or(tail);
    materials
        .iter()
        .position(|m| m.name == stem)
        .map(|i| i as u32)
}

fn vec3(value: &Value) -> Result<[f32; 3], Box<dyn Error>> {
    let array = value.as_array().ok_or("expected a three-number array")?;
    if array.len() != 3 {
        return Err("expected a three-number array".into());
    }
    Ok([
        array[0].as_f64().ok_or("invalid coordinate")? as f32,
        array[1].as_f64().ok_or("invalid coordinate")? as f32,
        array[2].as_f64().ok_or("invalid coordinate")? as f32,
    ])
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn local_json_texture_wins_over_same_named_map_material() {
        let directory =
            std::env::temp_dir().join(format!("ogk-local-texture-{}", std::process::id()));
        fs::create_dir_all(&directory).expect("temporary model folder should be created");
        let model_path = directory.join("item.json");
        fs::write(
            &model_path,
            r##"{
                "textures": { "surface": "local" },
                "elements": [{
                    "from": [0, 0, 0], "to": [16, 16, 16],
                    "faces": {
                        "north": { "texture": "#surface" },
                        "south": { "texture": "#surface" },
                        "east": { "texture": "#surface" },
                        "west": { "texture": "#surface" },
                        "up": { "texture": "#surface" },
                        "down": { "texture": "#surface" }
                    }
                }]
            }"##,
        )
        .expect("temporary model should be written");

        let mut materials = vec![MaterialDef {
            name: "local".into(),
            texture: directory.join("different.ppm"),
        }];
        register_adjacent_textures(&model_path, &mut materials)
            .expect("sidecar texture should register");
        assert_eq!(materials.len(), 2);
        assert_eq!(materials[1].texture, directory.join("local.ppm"));
        let mesh = load_model(&model_path, 0, &materials).expect("model should load");
        assert_eq!(mesh.vertices[0].material, 1);
        fs::remove_dir_all(directory).expect("temporary test folder should be removed");
    }
}
